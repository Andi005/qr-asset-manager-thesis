-- Inventory session mode (research question P2): an expected list, timed scans, a result.

create table inventory_session (
    id          bigint generated by default as identity primary key,
    name        varchar(120) not null,
    location_id bigint references location (id) on delete restrict,
    started_at  timestamptz  not null,
    started_by  varchar(60)  not null,
    finished_at timestamptz,
    constraint ck_inventory_dates check (finished_at is null or finished_at >= started_at)
);

create table inventory_expected (
    session_id bigint not null references inventory_session (id) on delete restrict,
    asset_id   bigint not null references asset (id) on delete restrict,
    constraint pk_inventory_expected primary key (session_id, asset_id)
);

create table inventory_scan (
    id         bigint generated by default as identity primary key,
    session_id bigint       not null references inventory_session (id) on delete restrict,
    scanned_at timestamptz  not null,
    raw_value  varchar(200) not null,
    asset_id   bigint references asset (id) on delete restrict,
    result     varchar(20)  not null,
    manual     boolean      not null default false,
    constraint ck_inventory_scan_result check (result in ('FOUND', 'UNEXPECTED', 'UNKNOWN', 'DUPLICATE'))
);

create index ix_inventory_scan_session on inventory_scan (session_id, scanned_at);
