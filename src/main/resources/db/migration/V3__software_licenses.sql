-- Software licenses with a seat count and an optional expiry date (null = perpetual).

create table software_license (
    id          bigint generated by default as identity primary key,
    name        varchar(120)  not null,
    vendor      varchar(80),
    seats_total integer       not null,
    expiry_date date,
    notes       varchar(2000),
    version     integer       not null default 0,
    created_at  timestamptz   not null,
    updated_at  timestamptz   not null,
    constraint ck_license_seats check (seats_total > 0)
);

create index ix_license_expiry on software_license (expiry_date);

-- One seat given to an employee XOR an asset. Open while released_at is null.
create table license_allocation (
    id           bigint generated by default as identity primary key,
    license_id   bigint      not null references software_license (id) on delete restrict,
    employee_id  bigint references employee (id) on delete restrict,
    asset_id     bigint references asset (id) on delete restrict,
    allocated_at timestamptz not null,
    allocated_by varchar(60) not null,
    released_at  timestamptz,
    released_by  varchar(60),
    constraint ck_allocation_holder check ((employee_id is null) <> (asset_id is null)),
    constraint ck_allocation_dates check (released_at is null or released_at >= allocated_at)
);

-- The same holder can't take two seats of the same license at once.
create unique index uq_allocation_open_employee on license_allocation (license_id, employee_id)
    where released_at is null and employee_id is not null;
create unique index uq_allocation_open_asset on license_allocation (license_id, asset_id)
    where released_at is null and asset_id is not null;
create index ix_allocation_license on license_allocation (license_id);
