-- Who had which asset, from when to when. A row is "open" while returned_at is null.
-- "Assigned" is never stored as a status: it is derived from the open row.

create table assignment (
    id          bigint generated by default as identity primary key,
    asset_id    bigint       not null references asset (id) on delete restrict,
    employee_id bigint       not null references employee (id) on delete restrict,
    assigned_at timestamptz  not null,
    assigned_by varchar(60)  not null,
    returned_at timestamptz,
    returned_by varchar(60),
    note        varchar(500),
    constraint ck_assignment_dates check (returned_at is null or returned_at >= assigned_at)
);

-- The core rule: an asset has at most one holder at a time.
create unique index uq_assignment_open_per_asset on assignment (asset_id) where returned_at is null;
create index ix_assignment_employee on assignment (employee_id);

-- A readable audit trail: who changed what, and when.
create table change_log (
    id          bigint generated by default as identity primary key,
    entity_type varchar(20)   not null,
    entity_id   bigint        not null,
    action      varchar(30)   not null,
    username    varchar(60)   not null,
    at          timestamptz   not null,
    details     varchar(4000),
    constraint ck_change_log_entity check (entity_type in ('ASSET', 'EMPLOYEE', 'LICENSE', 'IMPORT', 'USER'))
);

create index ix_change_log_entity on change_log (entity_type, entity_id);
create index ix_change_log_at on change_log (at desc);
