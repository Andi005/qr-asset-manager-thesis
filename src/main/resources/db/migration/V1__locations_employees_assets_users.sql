-- Core register: where things are, who holds them, the assets themselves, and who logs in.
-- Business rules that the database can enforce live here too (unique tag, unique serial,
-- allowed statuses and categories, warranty after purchase).

create table location (
    id         bigint generated by default as identity primary key,
    name       varchar(120) not null,
    created_at timestamptz  not null default now(),
    constraint uq_location_name unique (name)
);

create table employee (
    id         bigint generated by default as identity primary key,
    full_name  varchar(120) not null,
    email      varchar(160),
    department varchar(120),
    active     boolean      not null default true,
    created_at timestamptz  not null default now()
);

create unique index uq_employee_email on employee (lower(email)) where email is not null;

-- Tags look like IT-000123. The number comes from this sequence and is never reused.
create sequence asset_tag_seq start with 1;

create table asset (
    id                bigint generated by default as identity primary key,
    asset_tag         varchar(16)   not null,
    category          varchar(20)   not null,
    manufacturer      varchar(80),
    model             varchar(120)  not null,
    serial_number     varchar(64),
    purchase_date     date,
    warranty_end_date date,
    location_id       bigint references location (id) on delete restrict,
    status            varchar(20)   not null,
    notes             varchar(2000),
    version           integer       not null default 0,
    created_at        timestamptz   not null,
    updated_at        timestamptz   not null,
    constraint uq_asset_tag unique (asset_tag),
    -- PostgreSQL treats NULLs as distinct, so "unique when present" needs no extra index.
    constraint uq_asset_serial unique (serial_number),
    constraint ck_asset_tag check (asset_tag ~ '^IT-[0-9]{6}$'),
    constraint ck_asset_status check (status in ('IN_STOCK', 'IN_REPAIR', 'RETIRED')),
    constraint ck_asset_category check (category in
        ('LAPTOP', 'DESKTOP', 'MONITOR', 'PRINTER', 'PROJECTOR', 'NETWORK', 'PHONE', 'OTHER')),
    constraint ck_asset_warranty check
        (warranty_end_date is null or purchase_date is null or warranty_end_date >= purchase_date)
);

create index ix_asset_location on asset (location_id);
create index ix_asset_status on asset (status);
create index ix_asset_warranty on asset (warranty_end_date);

create table app_user (
    id            bigint generated by default as identity primary key,
    username      varchar(60)  not null,
    password_hash varchar(100) not null,
    display_name  varchar(120) not null,
    role          varchar(20)  not null,
    active        boolean      not null default true,
    created_at    timestamptz  not null default now(),
    constraint ck_app_user_role check (role in ('ADMIN', 'IT_STAFF', 'VIEWER'))
);

create unique index uq_app_user_username on app_user (lower(username));
